-- Sprint 2 #13: non-destructive schema upgrade for an existing PostgreSQL Sprint 1 database.
-- Run once or repeatedly. Existing reports and users are preserved.
CREATE TABLE IF NOT EXISTS "Contacts" (
    "Id" uuid PRIMARY KEY,
    "ReportId" uuid NOT NULL REFERENCES "Reports"("Id") ON DELETE RESTRICT,
    "OwnerId" uuid NOT NULL REFERENCES "Users"("Id") ON DELETE RESTRICT,
    "VisitorId" uuid NOT NULL REFERENCES "Users"("Id") ON DELETE RESTRICT,
    "CreatedAt" timestamptz NOT NULL,
    "LastMessageAt" timestamptz NULL,
    CONSTRAINT "CK_Contacts_DifferentUsers" CHECK ("OwnerId" <> "VisitorId")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Contacts_ReportId_VisitorId" ON "Contacts" ("ReportId", "VisitorId");
CREATE INDEX IF NOT EXISTS "IX_Contacts_OwnerId_LastMessageAt" ON "Contacts" ("OwnerId", "LastMessageAt");
CREATE INDEX IF NOT EXISTS "IX_Contacts_VisitorId" ON "Contacts" ("VisitorId");

CREATE TABLE IF NOT EXISTS "Messages" (
    "Id" uuid PRIMARY KEY,
    "ContactId" uuid NOT NULL REFERENCES "Contacts"("Id") ON DELETE CASCADE,
    "ReportId" uuid NOT NULL,
    "SenderId" uuid NOT NULL REFERENCES "Users"("Id") ON DELETE RESTRICT,
    "RecipientId" uuid NOT NULL REFERENCES "Users"("Id") ON DELETE RESTRICT,
    "Content" varchar(1500) NOT NULL,
    "CreatedAt" timestamptz NOT NULL,
    CONSTRAINT "CK_Messages_DifferentUsers" CHECK ("SenderId" <> "RecipientId")
);
CREATE INDEX IF NOT EXISTS "IX_Messages_ContactId_CreatedAt" ON "Messages" ("ContactId", "CreatedAt");
CREATE INDEX IF NOT EXISTS "IX_Messages_SenderId_CreatedAt" ON "Messages" ("SenderId", "CreatedAt");
CREATE INDEX IF NOT EXISTS "IX_Messages_RecipientId" ON "Messages" ("RecipientId");

CREATE TABLE IF NOT EXISTS "Directories" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(120) NOT NULL,
    "Location" varchar(200) NOT NULL,
    "InternalPhone" varchar(40) NOT NULL,
    "OfficeHours" varchar(140) NOT NULL,
    "Category" varchar(30) NOT NULL,
    "IsActive" boolean NOT NULL
);
