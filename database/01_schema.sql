-- PostgreSQL 17, schema tương ứng 5 entity trong backend/Domain/Entities.cs.
-- Chạy trên DB trống, hoặc sau khi EF EnsureCreated (CREATE TABLE IF NOT EXISTS).
-- Không xóa dữ liệu/không DROP TABLE. Tên cột PascalCase do EF Core đặt.
BEGIN;
CREATE TABLE IF NOT EXISTS "Users" (
    "Id" uuid PRIMARY KEY,
    "Email" varchar(180) NOT NULL,
    "FullName" varchar(120) NOT NULL,
    "PasswordHash" text NOT NULL,
    "Role" varchar(16) NOT NULL,
    "SuspendedUntil" timestamptz NULL,
    "EmailVerifiedAt" timestamptz NULL,
    "VerifyTokenHash" varchar(100) NULL,
    "VerifyExpiresAt" timestamptz NULL,
    "CreatedAt" timestamptz NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Users_Email" ON "Users"("Email");

CREATE TABLE IF NOT EXISTS "Categories" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(80) NOT NULL,
    "ParentId" integer NULL,
    CONSTRAINT "FK_Categories_Categories_ParentId"
        FOREIGN KEY ("ParentId") REFERENCES "Categories"("Id") ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_Categories_ParentId" ON "Categories"("ParentId");

CREATE TABLE IF NOT EXISTS "Locations" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(120) NOT NULL,
    "ParentId" integer NULL,
    CONSTRAINT "FK_Locations_Locations_ParentId"
        FOREIGN KEY ("ParentId") REFERENCES "Locations"("Id") ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_Locations_ParentId" ON "Locations"("ParentId");

CREATE TABLE IF NOT EXISTS "Reports" (
    "Id" uuid PRIMARY KEY,
    "UserId" uuid NOT NULL REFERENCES "Users"("Id") ON DELETE RESTRICT,
    "Type" varchar(8) NOT NULL,
    "Status" varchar(16) NOT NULL,
    "ItemName" varchar(140) NOT NULL,
    "Description" varchar(3500) NOT NULL,
    "PrivateIdentifier" varchar(200) NULL,
    "Color" varchar(80) NULL,
    "Brand" varchar(80) NULL,
    "LocationDetail" varchar(300) NULL,
    "CategoryId" integer NULL REFERENCES "Categories"("Id") ON DELETE RESTRICT,
    "LocationId" integer NULL REFERENCES "Locations"("Id") ON DELETE RESTRICT,
    "EventTime" timestamptz NOT NULL,
    "ExpiresAt" timestamptz NULL,
    "ExpirationNotifiedAt" timestamptz NULL,
    "CreatedAt" timestamptz NOT NULL,
    "UpdatedAt" timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_Reports_UserId" ON "Reports"("UserId");
CREATE INDEX IF NOT EXISTS "IX_Reports_CategoryId" ON "Reports"("CategoryId");
CREATE INDEX IF NOT EXISTS "IX_Reports_LocationId" ON "Reports"("LocationId");
CREATE INDEX IF NOT EXISTS "IX_Reports_Type_Status_EventTime" ON "Reports"("Type","Status","EventTime");

CREATE TABLE IF NOT EXISTS "Images" (
    "Id" uuid PRIMARY KEY,
    "ReportId" uuid NOT NULL REFERENCES "Reports"("Id") ON DELETE CASCADE,
    "Url" varchar(500) NOT NULL,
    "CreatedAt" timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_Images_ReportId" ON "Images"("ReportId");

-- Ticket báo cáo vi phạm; trong Final đây là CaseTicket, khác với bảng Reports là bài đăng.
CREATE TABLE IF NOT EXISTS "CaseTickets" (
    "Id" uuid PRIMARY KEY,
    "ReporterId" uuid NOT NULL REFERENCES "Users"("Id") ON DELETE RESTRICT,
    "ReportId" uuid NULL REFERENCES "Reports"("Id") ON DELETE SET NULL,
    "RoomId" uuid NULL,
    "Type" varchar(24) NOT NULL,
    "Reason" varchar(2000) NOT NULL,
    "Status" varchar(24) NOT NULL,
    "Resolution" varchar(1500) NULL,
    "ResolvedById" uuid NULL,
    "CreatedAt" timestamptz NOT NULL,
    "ResolvedAt" timestamptz NULL
);
CREATE INDEX IF NOT EXISTS "IX_CaseTickets_ReporterId" ON "CaseTickets"("ReporterId");
CREATE INDEX IF NOT EXISTS "IX_CaseTickets_ReportId" ON "CaseTickets"("ReportId");
CREATE INDEX IF NOT EXISTS "IX_CaseTickets_Status_CreatedAt" ON "CaseTickets"("Status","CreatedAt");
COMMIT;

